/**
 * i18n/<locale>/ → addon/Mealbook/Text_<locale>.lua, one for every language the
 * game has (a stub where there is no translation yet, so the TOC never names
 * a missing file): each client loads its own, through Text_[TextLocale].lua in
 * the TOCs, and English stays wherever a translation says nothing (Locale.lua).
 *
 *   i18n/<locale>/meta.json    { "plural": "one" | "fr", "flagged": true }
 *                              (flagged: a first translation, not reviewed by
 *                              a native reader)
 *   i18n/<locale>/words.json   { "English": "translation" }: every L["..."] of
 *                              the addon; i18n/words.json lists them
 *
 * A language not given its own folder may borrow another's (esMX: esES).
 * Only Mealbook's own words: the dishes' and ingredients' names come from the
 * game by their ids, in the client's language.
 *
 *   bun scripts/locales.ts            write the Text files
 *   bun scripts/locales.ts --check    fail if one isn't up to date, a word has
 *                                     no translation, a translation drops or
 *                                     reorders a blank, or prose has a semicolon
 *   bun scripts/locales.ts --keys     write i18n/words.json, every word to translate
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const I18N = join(ROOT, "i18n");
const ADDON = join(ROOT, "addon/Mealbook");
const LOCALES = ["enUS", "enGB", "deDE", "frFR", "esES", "esMX", "ruRU", "ptBR", "itIT", "koKR", "zhCN", "zhTW"];
const ENGLISH = new Set(["enUS", "enGB"]);
const BORROWS: Record<string, string> = { esMX: "esES" };

// every L["..."] of the addon's own files (the kit's copy aside: its words are
// the kit's, translated with the addon's when they appear)
function keys(): string[] {
  const found = new Set<string>();
  for (const f of readdirSync(ADDON).sort()) {
    if (!f.endsWith(".lua") || f.startsWith("Text_") || f === "Kit.lua") continue;
    const src = readFileSync(join(ADDON, f), "utf8");
    for (const m of src.matchAll(/\bL\["((?:[^"\\]|\\.)*)"\]/g)) found.add(m[1].replace(/\\"/g, '"').replace(/\\n/g, "\n"));
  }
  return [...found].sort();
}

const q = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;
const json = (file: string) => (existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {});
const blanks = (s: string) => [...s.matchAll(/%%|%[0-9.]*[sdf]/g)].map((m) => m[0]).filter((b) => b !== "%%");

// The game's own names a language's file carries, every language's whole
// (English one of them): the cooking skill line's (i18n/skill_line.json,
// written by scripts/recipes.ts from the client's SkillLine).
function namesLua(locale: string): string[] {
  const names: Record<string, string> = json(join(I18N, "skill_line.json"));
  if (!names[locale]) throw new Error(`i18n/skill_line.json names nothing in ${locale}: bun scripts/recipes.ts`);
  return [`ns.names({ skillLine = ${q(names[locale])} })`];
}

function luaFor(locale: string): string {
  const from = BORROWS[locale] && !existsSync(join(I18N, locale)) ? BORROWS[locale] : locale;
  const lines = [`-- Generated by scripts/locales.ts from i18n/${from}/: edit those, not this file.`];
  if (ENGLISH.has(locale) || !existsSync(join(I18N, from))) {
    lines.push(
      `-- (${ENGLISH.has(locale) ? "English: the words as the addon writes them" : "no translation yet: English words"}; the game's names)`,
      "local _, ns = ...",
      ...namesLua(locale),
    );
    return `${lines.join("\n")}\n`;
  }
  const meta = json(join(I18N, from, "meta.json"));
  const words: Record<string, string> = json(join(I18N, from, "words.json"));
  lines.push("local _, ns = ...", "ns.translate({", `  plural = ${q(meta.plural ?? "one")},`, "  words = {");
  for (const [k, v] of Object.entries(words)
    .filter(([, v]) => v)
    .sort(([a], [b]) => a.localeCompare(b)))
    lines.push(`    [${q(k)}] = ${q(v)},`);
  lines.push("  },", "})", ...namesLua(locale));
  return `${lines.join("\n")}\n`;
}

const args = process.argv.slice(2);
const all = keys();
if (args.includes("--keys")) {
  writeFileSync(join(I18N, "words.json"), `${JSON.stringify(Object.fromEntries(all.map((k) => [k, ""])), null, 2)}\n`);
  console.log(`i18n/words.json: ${all.length} words`);
  process.exit(0);
}
const check = args.includes("--check");
let bad = false;
const listed = Object.keys(json(join(I18N, "words.json")));
if (listed.join("\n") !== all.join("\n")) {
  console.error("✗ i18n/words.json is not the addon's words: bun scripts/locales.ts --keys");
  bad = true;
}
for (const locale of LOCALES) {
  const file = join(ADDON, `Text_${locale}.lua`);
  const want = luaFor(locale);
  const have = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (existsSync(join(I18N, locale))) {
    const words: Record<string, string> = json(join(I18N, locale, "words.json"));
    const missing = all.filter((k) => !words[k]);
    if (missing.length) {
      console.error(`✗ ${locale}: no translation for ${missing.map((m) => JSON.stringify(m)).join(", ")}`);
      bad = true;
    }
    for (const [k, v] of Object.entries(words)) {
      if (!all.includes(k)) console.log(`  ${locale}: no longer used: ${JSON.stringify(k)}`);
      if (blanks(k).join() !== blanks(v).join()) {
        console.error(`✗ ${locale}: the blanks differ: ${JSON.stringify(k)} → ${JSON.stringify(v)}`);
        bad = true;
      }
      if (v.includes(";")) {
        console.error(`✗ ${locale}: a semicolon in what players read: ${JSON.stringify(v)}`);
        bad = true;
      }
    }
  }
  if (have === want) continue;
  if (check) {
    console.error(`✗ ${file.slice(ROOT.length)} is not up to date: bun scripts/locales.ts`);
    bad = true;
  } else {
    writeFileSync(file, want);
    console.log(`wrote ${file.slice(ROOT.length)}`);
  }
}
for (const k of all)
  if (k.includes(";")) {
    console.error(`✗ a semicolon in what players read: ${JSON.stringify(k)}`);
    bad = true;
  }
if (bad) process.exit(1);
console.log(`✓ ${all.length} words, ${LOCALES.length} language files`);
